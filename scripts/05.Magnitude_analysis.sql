/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data and group results by specific dimensions.
    - For understanding data distribution across categories.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - GROUP BY, ORDER BY
===============================================================================
*/

-- Find total customers by countries
SELECT 
	country,
	count(customer_key) as TotalCustomers
from gold.dim_customers
group by country
order by TotalCustomers DESC


-- Find total customers by gender
SELECT 
	gender,
	count(customer_key) as TotalCustomers
from gold.dim_customers
group by gender
order by TotalCustomers DESC


-- Find total products by category
SELECT 
	category,
	count(product_key) as TotalProducts
from gold.dim_products
group by category
order by TotalProducts DESC


-- What is the average costs in each category?
SELECT 
	category,
	AVG(cost) as AvgCost_Category
from gold.dim_products
group by category
order by AvgCost_Category DESC


-- What is the total revenue generated for each category?
select 
	p.category,
	coalesce(sum(s.sales_amount),0) TotalRevenue_category
from gold.dim_products p
left join gold.fact_sales s
on p.product_key = s.product_key
group by category
having coalesce(sum(s.sales_amount),0) > 0
order by TotalRevenue_category DESC


-- What is the total revenue generated by each customer?
select 
	concat(c.first_name,' ',c.last_name) CustomerName,
	sum(s.sales_amount) TotalRevenue_customer
from gold.dim_customers c
left join gold.fact_sales s
on c.customer_key = s.customer_key
group by concat(c.first_name,' ',c.last_name)
order by TotalRevenue_customer DESC


-- What is the distribution of sold items across countries?
select 
	country,
	count(quantity) ItemsDist
from gold.dim_customers c
left join gold.fact_sales s
on c.customer_key = s.customer_key
left join gold.dim_products p
on s.product_key = p.product_key
group by country
order by ItemsDist DESC